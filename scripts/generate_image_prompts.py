    n = 0
    for i, (title, overview, tip_title, tip_body, summary_body) in enumerate(lessons, 1):
        lid = f"l{i}"
        out.append(f"\n## L{i} {title} (`{skill_id}-{lid}`)\n\n")
        first_sentence = overview.split("。")[0] + "。" if "。" in overview else overview
        slides = [
            ("s1", title,
             ["本文：", first_sentence],
             f"- レッスン「{title}」の導入ビジュアル。テーマが一目で伝わる",
             "やさしい導入", False),
            ("s2", f"{title}を理解しよう",
             ["本文：", overview],
             "- 概念を図解。文字多めでも読みやすくレイアウト",
             "わかりやすい学習", False),
            ("s3", "もう一歩深める",
             ["本文：", "今日のポイントを、日常の場面に当てはめてみよう。", "", overview],
             "- 学校・友だち・自宅など学生の日常シーンで具体化",
             "身近・実践的", False),
            ("s5", tip_title,
             ["本文："] + tip_body.split("\n"),
             "- ポイントカード風。すぐ使えるヒント",
             "気軽・実用", True),
            ("s7", "今日のまとめ",
             ["本文："] + summary_body.split("\n"),
             "- まとめ・次へのつなぎ。前向きな区切り",
             "前向き・定着", False),
        ]
        for sid, t, texts, visual, tone, tip in slides:
            fn = f"{skill_id}-{lid}-{sid}.png"
            out.append(prompt_block(fn, folder, title, sid, t, texts, visual, tone, tip))
            n += 1
    return "".join(out), n


