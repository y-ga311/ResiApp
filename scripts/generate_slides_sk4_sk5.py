#!/usr/bin/env python3
"""Generate slides-sk4 and slides-sk5 TypeScript files."""

from pathlib import Path
from textwrap import dedent

OUT = Path("/Users/yamamotogaku/Dropbox/Resilient/lib")


def esc(s: str) -> str:
    return s.replace("\\", "\\\\").replace("`", "\\`").replace("${", "\\${")


def slide_intro(emoji, title, body):
    return dedent(f"""\
    {{
      id: "s1", type: "intro",
      emoji: "{emoji}",
      title: "{title}",
      body: `{esc(body)}`,
    }}""")


def slide_learn(sid, emoji, title, body):
    return dedent(f"""\
    {{
      id: "{sid}", type: "learn",
      emoji: "{emoji}",
      title: "{title}",
      body: `{esc(body)}`,
    }}""")


def slide_quiz(sid, question, options, explanation):
    opts = ",\n".join(
        f'          {{ label: "{o[0]}", correct: {str(o[1]).lower()} }}' for o in options
    )
    return dedent(f"""\
    {{
      id: "{sid}", type: "quiz",
      quiz: {{
        question: "{question}",
        options: [
{opts}
        ],
        explanation: "{explanation}",
      }},
    }}""")


def slide_tip(sid, emoji, title, body):
    return dedent(f"""\
    {{
      id: "{sid}", type: "tip",
      emoji: "{emoji}",
      title: "{title}",
      body: `{esc(body)}`,
    }}""")


def slide_work(sid, emoji, title, body, prompt, hint):
    return dedent(f"""\
    {{
      id: "{sid}", type: "work",
      emoji: "{emoji}",
      title: "{title}",
      body: `{esc(body)}`,
      work: {{
        prompt: "{prompt}",
        hint: "{hint}",
      }},
    }}""")


def slide_summary(sid, emoji, title, body):
    return dedent(f"""\
    {{
      id: "{sid}", type: "summary",
      emoji: "{emoji}",
      title: "{title}",
      body: `{esc(body)}`,
    }}""")


def lesson(key, slides):
    joined = ",\n".join(slides)
    return f'  "{key}": [\n{joined},\n  ]'


def write_file(name, export_name, header, lessons_dict):
    blocks = [lesson(k, v) for k, v in lessons_dict.items()]
    content = f'''import type {{ Slide }} from "./types";

// ─────────────────────────────────────────────────────────────
// {header}
// ─────────────────────────────────────────────────────────────

export const {export_name}: Record<string, Slide[]> = {{

{chr(10).join(blocks + [""])}}};
'''
    path = OUT / name
    path.write_text(content, encoding="utf-8")
    print("wrote", path, "lessons=", len(lessons_dict))


